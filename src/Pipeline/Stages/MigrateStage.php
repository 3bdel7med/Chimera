<?php

declare(strict_types=1);

namespace Abdelhmed\Chimera\Pipeline\Stages;

use Abdelhmed\Chimera\Contracts\CheckpointStore;
use Abdelhmed\Chimera\Contracts\MigrationRunner;
use Abdelhmed\Chimera\Contracts\ProgressTracker;
use Abdelhmed\Chimera\Contracts\Reporter;
use Abdelhmed\Chimera\Data\GeneratedFile;
use Abdelhmed\Chimera\Enums\FileType;
use Abdelhmed\Chimera\Enums\Phase;
use Abdelhmed\Chimera\Pipeline\MorphContext;
use Abdelhmed\Chimera\Pipeline\Stage;
use Throwable;

/** Runs only the migrations this run created. */
final class MigrateStage implements Stage
{
    public function __construct(
        private readonly MigrationRunner $migrations,
        private readonly CheckpointStore $checkpoints,
        private readonly Reporter $reporter,
        private readonly ProgressTracker $progress,
    ) {
    }

    public function handle(MorphContext $context): void
    {
        if (! $context->runMigrations || $context->report === null || $context->checkpointId === null) {
            return;
        }

        $paths = array_values(array_map(
            fn (GeneratedFile $f) => $f->path(),
            array_filter(
                $context->generated,
                fn (GeneratedFile $f) => $f->type() === FileType::Migration && in_array($f->path(), $context->report->created, true),
            ),
        ));

        if ($paths === []) {
            return;
        }

        $this->progress->phase(Phase::Migrate, 'only the '.count($paths).' migration(s) generated by this run');

        // Recorded before running so a half-finished migration can still be rolled back.
        $this->checkpoints->recordMigrations($context->checkpointId, $paths);

        try {
            $this->reporter->spin('Migrating...', fn () => $this->migrations->migrate($paths));
        } catch (Throwable $e) {
            $this->reporter->error('Migration failed: '.$e->getMessage());
            $context->halt("Migration failed. Run `php artisan chimera:rollback {$context->checkpointId}` to restore your project.", true);

            return;
        }

        $this->progress->phaseDone(Phase::Migrate, count($paths).' migration(s) executed');
    }
}
