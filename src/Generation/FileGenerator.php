<?php

declare(strict_types=1);

namespace Abdelhmed\Chimera\Generation;

use Abdelhmed\Chimera\Contracts\LlmClient;
use Abdelhmed\Chimera\Contracts\ProjectFiles;
use Abdelhmed\Chimera\Data\Blueprint;
use Abdelhmed\Chimera\Data\FileSpec;
use Abdelhmed\Chimera\Data\GeneratedFile;
use Abdelhmed\Chimera\Enums\FileAction;
use Abdelhmed\Chimera\Enums\FileType;
use Abdelhmed\Chimera\Exceptions\GenerationException;
use Abdelhmed\Chimera\Exceptions\ResponseTruncatedException;
use Abdelhmed\Chimera\Support\PromptRepository;
use Closure;

/**
 * Phase 2: turns blueprint entries into code, a batch of files per AI call.
 * A batch that is too big for one reply is split in half automatically, and PHP that does not parse is re-requested.
 */
final class FileGenerator
{
    public function __construct(
        private readonly LlmClient $llm,
        private readonly PromptRepository $prompts,
        private readonly BatchPromptBuilder $builder,
        private readonly GeneratedFileValidator $validator,
        private readonly ProjectFiles $files,
        private readonly int $maxSyntaxRetries = 2,
    ) {
    }

    /**
     * @param  array<string, mixed>  $projectContext
     * @param  list<FileSpec>  $batch
     * @param  list<GeneratedFile>  $done  files generated by earlier batches
     * @param  string|null  $feedback  problems with an earlier version of these files, sent with the first request
     * @return list<GeneratedFile>
     */
    public function generate(string $prompt, Blueprint $blueprint, array $projectContext, array $batch, array $done = [], ?string $feedback = null): array
    {
        $system = $this->prompts->render('generate.system');

        $files = $this->validated(
            fn (?string $retry) => $this->requestBatch($system, $prompt, $blueprint, $projectContext, $batch, $done, $retry ?? $feedback)
        );

        $order = array_flip(array_map(fn (FileSpec $s) => $s->path, $batch));
        usort($files, fn (GeneratedFile $a, GeneratedFile $b) => $order[$a->path()] <=> $order[$b->path()]);

        return $files;
    }

    /**
     * Ask the model to fix the generated files after a failed test run. Returns only the files it changed.
     *
     * @param  list<GeneratedFile>  $generated
     * @return list<GeneratedFile>
     */
    public function heal(string $prompt, Blueprint $blueprint, array $generated, string $testOutput): array
    {
        $current = [];
        foreach ($generated as $file) {
            if ($this->files->exists($file->path())) {
                $current[$file->path()] = $this->files->get($file->path());
            }
        }

        $system = $this->prompts->render('heal.system');

        return $this->validated(function (?string $feedback) use ($system, $prompt, $blueprint, $current, $testOutput, $generated): array {
            $user = $this->builder->buildHeal($prompt, $blueprint, $current, $testOutput, $feedback);
            $healed = [];

            foreach ($this->index($this->llm->generateJson($system, $user, FileBatchSchema::definition())) as $path => $content) {
                $healed[] = new GeneratedFile($this->healSpec($path, $generated), $content);
            }

            if ($healed === []) {
                throw new GenerationException('The AI did not return any fixes.');
            }

            return $healed;
        });
    }

    /**
     * @param  Closure(?string): list<GeneratedFile>  $request
     * @return list<GeneratedFile>
     */
    private function validated(Closure $request): array
    {
        $feedback = null;

        for ($attempt = 0; $attempt <= $this->maxSyntaxRetries; $attempt++) {
            $files = $request($feedback);

            if (($errors = $this->validator->validate($files)) === []) {
                return $files;
            }

            $feedback = implode("\n", array_map(fn (string $path, string $error) => "- {$path}: {$error}", array_keys($errors), $errors));
        }

        throw new GenerationException("The AI kept returning invalid code after ".($this->maxSyntaxRetries + 1)." attempts:\n{$feedback}");
    }

    /**
     * @param  array<string, mixed>  $projectContext
     * @param  list<FileSpec>  $batch
     * @param  list<GeneratedFile>  $done
     * @return list<GeneratedFile>
     */
    private function requestBatch(string $system, string $prompt, Blueprint $blueprint, array $projectContext, array $batch, array $done, ?string $feedback): array
    {
        $user = $this->builder->build($prompt, $blueprint, $projectContext, $batch, $done, $feedback);

        try {
            $raw = $this->llm->generateJson($system, $user, FileBatchSchema::definition());
        } catch (ResponseTruncatedException $e) {
            if (count($batch) === 1) {
                throw new GenerationException("{$batch[0]->path} is too large for a single AI reply. Raise gemini.max_output_tokens or describe a smaller feature.", 0, $e);
            }

            [$first, $second] = array_chunk($batch, (int) ceil(count($batch) / 2));
            $head = $this->requestBatch($system, $prompt, $blueprint, $projectContext, $first, $done, $feedback);
            $tail = $this->requestBatch($system, $prompt, $blueprint, $projectContext, $second, [...$done, ...$head], $feedback);

            return [...$head, ...$tail];
        }

        $byPath = $this->index($raw);
        $generated = [];
        $missing = [];

        foreach ($batch as $spec) {
            isset($byPath[$spec->path])
                ? $generated[] = new GeneratedFile($spec, $byPath[$spec->path])
                : $missing[] = $spec;
        }

        if ($missing === []) {
            return $generated;
        }

        if (count($missing) === count($batch)) {
            throw new GenerationException('The AI returned no usable content for: '.implode(', ', array_map(fn (FileSpec $s) => $s->path, $missing)));
        }

        return [...$generated, ...$this->requestBatch($system, $prompt, $blueprint, $projectContext, $missing, [...$done, ...$generated], $feedback)];
    }

    /** @return array<string, string> normalised path => content (markdown fences stripped) */
    private function index(array $raw): array
    {
        $map = [];

        foreach ((array) ($raw['files'] ?? []) as $item) {
            if (! is_array($item)) {
                continue;
            }

            $path = (string) preg_replace('#^(\./|/)+#', '', str_replace('\\', '/', trim((string) ($item['path'] ?? $item['filePath'] ?? ''))));
            $content = $item['content'] ?? $item['code'] ?? null;

            if ($path !== '' && is_string($content) && trim($content) !== '') {
                $map[$path] = $this->stripFences($content);
            }
        }

        return $map;
    }

    private function stripFences(string $content): string
    {
        return preg_match('/^\s*```[a-zA-Z]*\R(.*?)\R```\s*$/s', $content, $m) === 1 ? $m[1] : $content;
    }

    /** @param list<GeneratedFile> $generated */
    private function healSpec(string $path, array $generated): FileSpec
    {
        foreach ($generated as $file) {
            if ($file->path() === $path) {
                return $file->spec->with(action: FileAction::Modify);
            }
        }

        return new FileSpec(
            $path,
            FileType::guessFromPath($path),
            $this->files->exists($path) ? FileAction::Modify : FileAction::Create,
            'Added while fixing failing tests',
        );
    }
}
